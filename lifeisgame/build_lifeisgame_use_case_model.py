def cell(root, cell_id, value="", style="", parent="1", vertex=False, edge=False, source=None, target=None):
    attrs = {"id": cell_id, "value": value, "style": style, "parent": parent}
    if vertex:
        attrs["vertex"] = "1"
    if edge:
        attrs["edge"] = "1"
    if source:
        attrs["source"] = source
    if target:
        attrs["target"] = target
    return ET.SubElement(root, "mxCell", attrs)


def geometry(node, x=None, y=None, width=None, height=None, relative=False):
    attrs = {"as": "geometry"}
    if relative:
        attrs["relative"] = "1"
    else:
        attrs.update({"x": str(x), "y": str(y), "width": str(width), "height": str(height)})
    ET.SubElement(node, "mxGeometry", attrs)


class Page:
    def __init__(self, mxfile, name, page_width=1700, page_height=1050):
        self.diagram = ET.SubElement(mxfile, "diagram", {"id": f"page-{len(mxfile)}", "name": name})
        self.model = ET.SubElement(
            self.diagram,
            "mxGraphModel",
            {
                "dx": "1400",
                "dy": "900",
                "grid": "1",
                "gridSize": "10",
                "guides": "1",
                "tooltips": "1",
                "connect": "1",
                "arrows": "1",
                "fold": "1",
                "page": "1",
                "pageScale": "1",
                "pageWidth": str(page_width),
                "pageHeight": str(page_height),
                "math": "0",
                "shadow": "0",
            },
        )
        self.root = ET.SubElement(self.model, "root")
        ET.SubElement(self.root, "mxCell", {"id": "0"})
        ET.SubElement(self.root, "mxCell", {"id": "1", "parent": "0"})
        self.counter = 1

    def next_id(self, prefix):
        self.counter += 1
        return f"{prefix}-{self.counter}"

    def boundary(self, title):
        node = cell(
            self.root,
            self.next_id("boundary"),
            f"<b>Система LifeIsGame</b><br><font style='font-size:13px'>{title}</font>",
            "rounded=0;whiteSpace=wrap;html=1;verticalAlign=top;align=center;spacingTop=14;"
            "strokeWidth=2;strokeColor=#1F2937;fillColor=#F8FAFC;fontColor=#111827;fontSize=18;",
            vertex=True,
        )
        geometry(node, 260, 60, 1180, 860)
        return node.attrib["id"]

    def title(self, text, subtitle=None):
        value = f"<b>{text}</b>"
        if subtitle:
            value += f"<br><font style='font-size:13px;color:#475569'>{subtitle}</font>"
        node = cell(
            self.root,
            self.next_id("title"),
            value,
            "text;html=1;align=center;verticalAlign=middle;whiteSpace=wrap;fontSize=24;fontColor=#0F172A;",
            vertex=True,
        )
        geometry(node, 180, 15, 1340, 60)
        return node.attrib["id"]

    def actor(self, label, x, y, side="primary"):
        fill = "#E0F2FE" if side == "primary" else "#FEF3C7"
        node = cell(
            self.root,
            self.next_id("actor"),
            label,
            "shape=umlActor;verticalLabelPosition=bottom;verticalAlign=top;html=1;"
            f"outlineConnect=0;fontSize=14;fontColor=#111827;fillColor={fill};strokeColor=#111827;",
            vertex=True,
        )
        geometry(node, x, y, 120, 120)
        return node.attrib["id"]

    def use_case(self, uc_id, label, x, y, w=270, h=74, fish=False):
        color = "#F3E8FF" if fish else "#DBEAFE"
        border = "#7E22CE" if fish else "#2563EB"
        value = f"<b>{uc_id}</b><br>{label}"
        if fish:
            value += "<br><font style='font-size:10px;color:#6B21A8'>уровень рыб</font>"
        node = cell(
            self.root,
            self.next_id("uc"),
            value,
            "ellipse;whiteSpace=wrap;html=1;align=center;verticalAlign=middle;"
            f"fontSize=14;fontColor=#111827;fillColor={color};strokeColor={border};strokeWidth=2;",
            vertex=True,
        )
        geometry(node, x, y, w, h)
        return node.attrib["id"]

    def association(self, source, target):
        node = cell(
            self.root,
            self.next_id("assoc"),
            "",
            "edgeStyle=none;rounded=0;html=1;"
            "endArrow=none;startArrow=none;strokeColor=#475569;strokeWidth=1.5;",
            edge=True,
            source=source,
            target=target,
        )
        geometry(node, relative=True)

    def include(self, source, target):
        node = cell(
            self.root,
            self.next_id("include"),
            "«include»",
            "edgeStyle=orthogonalEdgeStyle;rounded=0;orthogonalLoop=1;jettySize=auto;html=1;"
            "dashed=1;dashPattern=8 6;endArrow=open;endFill=0;strokeColor=#7E22CE;"
            "strokeWidth=2;fontSize=13;fontColor=#6B21A8;labelBackgroundColor=#FFFFFF;",
            edge=True,
            source=source,
            target=target,
        )
        geometry(node, relative=True)

    def note(self, text, x, y, w, h, color="#FFF7D6"):
        node = cell(
            self.root,
            self.next_id("note"),
            text,
            "shape=note;whiteSpace=wrap;html=1;align=left;verticalAlign=top;spacing=10;"
            f"fontSize=12;fontColor=#374151;fillColor={color};strokeColor=#D6B656;",
            vertex=True,
        )
        geometry(node, x, y, w, h)
        return node.attrib["id"]

    def card(self, title, body, x, y, w, h, color="#FFFFFF"):
        node = cell(
            self.root,
            self.next_id("card"),
            f"<b>{title}</b><br><br>{body}",
            "rounded=1;whiteSpace=wrap;html=1;align=left;verticalAlign=top;spacing=14;arcSize=12;"
            f"fontSize=14;fontColor=#1F2937;fillColor={color};strokeColor=#94A3B8;strokeWidth=1.5;",
            vertex=True,
        )
        geometry(node, x, y, w, h)
        return node.attrib["id"]


